"""Freshwater fish species recognised in Polish Wikipedia lake articles.

Each species has:
  key      - stable identifier used in the data file
  name     - Polish name shown on the website
  latin    - scientific name
  patterns - regular expressions for the Polish name in its inflected forms. They are matched
             case-sensitively against lower-case text, so place names written with a capital
             letter (for example the village "Szczupaki") are not matched. More specific
             multi-word names are listed before the generic ones and win over them.
  seeds    - titles of Polish Wikipedia articles about the species. A link from a lake article
             to one of these articles (or to a redirect pointing at it) counts as a mention.
             A seed only counts if the lead sentence of that article contains the species'
             epithet from `latin` (or the genus for genus-level entries) and the article is not a
             disambiguation page, so a seed can never point at an unrelated article.
  lead_tokens - optional extra words accepted in that lead sentence (older scientific names
             still used by Polish Wikipedia).

Ambiguous word forms are left out on purpose, e.g. "sumie" ("w sumie" means "in total"),
"jazie" (also a form of "jaz", a weir) and "linie" (also "line"). The fish "koza" is only
recognised through a link, because the word also means "goat".
"""

